import type { Generator } from '@/generators/define'
import type { AuroraInput } from '@goatsoft/aurora-format'
import { assertAurora, stringifyAurora } from '@goatsoft/aurora-format'
import { describe, expect, inject, it } from 'vitest'
import { GENERATORS, loadGenerators } from '@/generators/index'
import { COLOR_ROLES } from '@/generators/roles'
import { validateDocument } from '@/validate'

/**
 * Generator reference docs and starter presets are generated from the generators themselves, so
 * they can't drift. Regenerate with `pnpm test -u`.
 */
await loadGenerators()
const root = inject('root')
const builtins = Object.values(GENERATORS).filter((g) => !g.id.startsWith('test-'))

/** Each generator alone, with its own palette and defaults. Grain is a layer to add, not a default. */
function starter(g: Generator): AuroraInput {
  return { format: 'aurora', version: 1, name: `${g.label} starter`, palette: [...g.palette], layers: [{ type: g.id }] }
}

function markdown(g: Generator): string {
  const rows = Object.entries(g.params).map(([name, p]) =>
    `| \`${name}\` | ${p.label} | ${p.default}${p.unit ? ` ${p.unit}` : ''} | ${p.min} to ${p.max} | ${p.description} |`)
  const roles = COLOR_ROLES[g.id] ?? []
  const colours = g.palette.map((c, i) => `| ${i} | ${roles[i] ?? ''} | \`${c}\` |`)
  const notes = g.requires?.length ? `\n## Implementation note\n\nBuilt on the shared noise library: ${g.requires.map((m) => `\`${m}\``).join(', ')}.\n` : ''
  return `---
order: ${builtins.indexOf(g) + 1}
---

# ${g.label} (\`${g.id}\`)

${g.description}

\`\`\`aurora
${stringifyAurora(starter(g)).trim()}
\`\`\`

This is [\`presets/starters/${g.id}.aurora\`](/presets/starters/${g.id}.aurora): the generator alone, with its defaults.

## Colours

A layer's \`colors\` picks ${g.colors} palette colour${g.colors === 1 ? '' : 's'}, in the order below. To recolour part of the background, change the palette colour in that position.

| Position | Paints | Default |
|---|---|---|
${colours.join('\n')}

## Parameters

Every parameter is optional; one you leave out uses its default.

| Name | Label | Default | Range | What it does |
|---|---|---|---|---|
${rows.join('\n')}
${notes}`
}

describe('generated generator docs and starters', () => {
  it.each(builtins.map((g) => [g.id, g] as const))('%s', async (id, g) => {
    expect(await validateDocument(assertAurora(starter(g)))).toEqual([])
    expect(COLOR_ROLES[id], 'every built-in says what each palette colour paints (generators/roles.ts)').toHaveLength(g.colors)
    await expect(markdown(g)).toMatchFileSnapshot(`${root}/docs/generators/${id}.md`)
    await expect(stringifyAurora(starter(g))).toMatchFileSnapshot(`${root}/presets/starters/${id}.aurora`)
  })

  it('indexes every generator', async () => {
    const list = builtins.map((g) => `| [${g.label}](${g.id}.md) | \`${g.id}\` | ${g.description} |`).join('\n')
    // Generated by packages/core/test/docs.test.ts; regenerate with `pnpm test -u`.
    await expect(`---\norder: 0\n---\n\n# Generators\n\nEach generator draws one kind of background. A layer's \`type\` names its generator.\n\n| Generator | Id | Description |\n|---|---|---|\n${list}\n`).toMatchFileSnapshot(`${root}/docs/generators/README.md`)
  })
})
